/* PCM16 → μ-law 编码（ITU-T G.711 算法）
 *   s = sign (0=正, 1=负)
 *   取绝对值（钳位到 32635）
 *   求 exponent 3bit + mantissa 4bit
 *   组合编码：1 0 exp mantissa → 5bit + 3bit = 8bit 补位
 *   反码 + 1（避免连续 0 带静音检测） */
static uint8_t pcm_to_ulaw(int16_t sample)
{
    int s = (sample < 0) ? 0 : 1;
    if (!s) sample = -sample;
    if (sample > 32635) sample = 32635;
    sample += 33;
    uint8_t exp = 7;
    uint16_t mask = 0x1000;
    while (exp > 0 && !(sample & mask)) {
        --exp;
        mask >>= 1;
    }
    uint8_t mant = (sample >> (exp + 3)) & 0x0F;
    uint8_t code = (uint8_t)(~(s << 7 | exp << 4 | mant));
    return (uint8_t)(code + 0x02); /* 反码 + 0x02（避免连续 0） */
}

void g711_pcm16_to_ulaw(const int16_t *in, uint8_t *out, size_t n)
{
    for (size_t i = 0; i < n; ++i) out[i] = pcm_to_ulaw(in[i]);
}
